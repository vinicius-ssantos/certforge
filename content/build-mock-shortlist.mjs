// Writes docs/release/mock-exam-review-shortlist.md: the shortest set of reviews that would make
// a mock exam startable, and which questions to put in front of a reviewer first.
//
// This selects. It does not review. Nothing it writes says a question is correct — ADR 0005 puts
// that in a named human's hands, and "unflagged" here means only that the mechanical triage in
// docs/release/review-triage.md recorded nothing against the question.
//
// Run from the repository root: node content/build-mock-shortlist.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { readPack, readReviewRecord, reviewStatusOf } from "./pack.mjs";

/** MockExamBlueprintCatalog: questionsPerTopic for 1Z0-830. The planner refuses below it. */
const PER_TOPIC = 5;

const PACK = "content/java-se-21";
const TRIAGE = "docs/release/review-triage.md";
const PACKET = "docs/release/content-review-packet.md";
const OUT = "docs/release/mock-exam-review-shortlist.md";

const questions = readPack(PACK);
const record = readReviewRecord(PACK);
const triage = readFileSync(TRIAGE, "utf8");
const packet = readFileSync(PACKET, "utf8");

/** Where each question lives in the packet, so the shortlist can point at it. */
const anchors = new Map();
for (const m of packet.matchAll(/^## (\d+)\. (t\d{2}-[a-z0-9-]+)$/gm)) {
  anchors.set(m[2], `#${m[1]}-${m[2]}`);
}

/** The topic names the packet already prints, rather than a second copy of them here. */
const topicNames = new Map();
for (const m of packet.matchAll(/^\| \d+ \| \[`(t\d{2}-[a-z0-9-]+)`\]\([^)]*\) \| ([^|]+) \|/gm)) {
  topicNames.set(m[1].slice(0, 3), m[2].trim());
}

/**
 * The triage names a question in bold and then discusses it until it names the next one. A
 * question counts as unflagged when its own passage says so in those words and carries no
 * bulleted flag.
 */
const passages = new Map();
const mentions = [...triage.matchAll(/\*\*(t\d{2}-[a-z0-9-]+)\*\*/g)];
for (let i = 0; i < mentions.length; i += 1) {
  if (passages.has(mentions[i][1])) continue;
  const end = i + 1 < mentions.length ? mentions[i + 1].index : triage.length;
  passages.set(mentions[i][1], triage.slice(mentions[i].index, end));
}

const unflagged = (name) => {
  const passage = passages.get(name) ?? "";
  return /Nothing flagged\./.test(passage) && !/^\s*-\s+\*/m.test(passage);
};

const byTopic = new Map();
for (const question of questions) {
  const topic = question.name.slice(0, 3);
  const status = reviewStatusOf(record, question);
  const bucket = byTopic.get(topic) ?? { publishable: 0, clean: [], flagged: 0 };
  if (status.state === "reviewed" && status.verdict === "APPROVED") bucket.publishable += 1;
  else if (status.state === "unreviewed") {
    if (unflagged(question.name)) bucket.clean.push(question.name);
    else bucket.flagged += 1;
  }
  byTopic.set(topic, bucket);
}

const short = [];
let needed = 0;
for (const topic of [...byTopic.keys()].sort()) {
  const bucket = byTopic.get(topic);
  const gap = Math.max(0, PER_TOPIC - bucket.publishable);
  if (gap === 0) continue;
  needed += gap;
  short.push({
    topic,
    gap,
    publishable: bucket.publishable,
    picks: bucket.clean.slice(0, gap),
    spare: Math.max(0, bucket.clean.length - gap),
  });
}

const lines = [
  "# The shortest path to a startable mock exam",
  "",
  `Generated by \`content/build-mock-shortlist.mjs\` from the pack, [the triage](review-triage.md)`,
  "and [the review packet](content-review-packet.md). **Regenerate it rather than editing it.**",
  "",
  "## What this is",
  "",
  "A mock exam cannot start on an installation this project's tooling produces: the blueprint",
  "wants five published questions in every topic, and publishing only ever emits questions a",
  "person has reviewed and approved (#138).",
  "",
  `As the pack stands, **${needed} more approved reviews, across ${short.length} topics**, closes that gap.`,
  "",
  "This document chooses which questions to put in front of a reviewer first. **It is a selection,**",
  "**not a review.** Nothing here says a question is correct; ADR 0005 puts that in a named human's",
  "hands and nothing generated by a machine changes it.",
  "",
  '"Unflagged" means only that the triage recorded nothing against the question. A reviewer who',
  "rejects one takes the next: every topic below keeps spares.",
  "",
  "## Where the pack stands",
  "",
  "| Topic | Publishable | Still needed | Unflagged spares beyond these |",
  "|---|---|---|---|",
];

for (const row of short) {
  const name = topicNames.get(row.topic) ?? row.topic;
  lines.push(`| \`${row.topic}\` ${name} | ${row.publishable} of ${PER_TOPIC} | ${row.gap} | ${row.spare} |`);
}

lines.push("");
lines.push("Any topic already at five is complete and is not listed.");
lines.push("");
lines.push("## The shortlist");
lines.push("");

for (const row of short) {
  lines.push(`### \`${row.topic}\` — ${topicNames.get(row.topic) ?? ""}`);
  lines.push("");
  if (row.picks.length < row.gap) {
    lines.push(
      `> Only ${row.picks.length} unflagged question(s) remain here against ${row.gap} needed. The rest of`,
      "> this topic carries triage flags, so closing it means reviewing a flagged question or fixing one.",
      "",
    );
  }
  for (const pick of row.picks) {
    lines.push(`- [\`${pick}\`](content-review-packet.md${anchors.get(pick) ?? ""})`);
  }
  lines.push("");
}

lines.push("## Recording a verdict");
lines.push("");
lines.push("Unchanged from the packet, which is the document to actually read:");
lines.push("");
lines.push("1. Answer the question yourself, **without** looking at the answer key.");
lines.push("2. Compare with the key and the reasons. Run the code if there is any doubt.");
lines.push("3. Make the content-policy checks yourself. Anything ambiguous or disputed must not be published.");
lines.push(
  "4. Record the verdict in `content/java-se-21/review.json` with the digest printed under the question.",
);
lines.push("   **A question you did not look at must not get an entry.**");
lines.push("5. Approve it in the editorial desk, as a person other than its author.");
lines.push("");
lines.push("`just publish-content` then carries exactly those verdicts, and the mock becomes startable.");
lines.push("");

writeFileSync(OUT, lines.join("\n"));
console.log(`${OUT}: ${needed} review(s) needed across ${short.length} topic(s)`);
