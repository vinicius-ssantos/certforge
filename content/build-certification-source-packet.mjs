// Writes docs/release/certification-source-packet.md: for every CERTIFICATION-kind content pack,
// the exam's verified source (provider, version, read date, URL, digest) beside every question's
// claimed objective -- and, computed from the same migration that seeded the exam's objectives,
// which ones no published question claims yet.
//
// This exists because content-policy.md's "Certification source governance" section promises a
// reviewer sees a question's claimed objective next to the exam's verification status, source and
// date (#177). The promise was true at the catalog-admin API level (ADR 0017/#165) but not in this
// project's actual review workflow, which is a generated packet a person reads, not a live screen
// a catalog administrator queries. This script is the missing half.
//
// It reads two things that are each already a single source of truth and never duplicates either:
// pack.json's `certification` block (the verified reading this project's own author recorded) and
// the migration that seeded that exam's full objective list (the curriculum as read, including
// objectives this round's pack does not yet cover). Neither is re-verified here -- that would be
// re-deriving ADR 0005's human judgement from a machine, which is exactly what this project refuses
// to do. This only juxtaposes what both already say.
//
// Run from the repository root: node content/build-certification-source-packet.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { readManifestPack } from "./manifest-pack.mjs";

const CONTENT_DIR = "content";
const MIGRATION_DIR = "src/main/resources/db/migration";
const OUT = "docs/release/certification-source-packet.md";

function certificationPackDirs() {
  return readdirSync(CONTENT_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => join(CONTENT_DIR, entry.name))
    .filter((dir) => {
      try {
        return JSON.parse(readFileSync(join(dir, "pack.json"), "utf8")).trackKind === "CERTIFICATION";
      } catch {
        return false;
      }
    })
    .sort();
}

/**
 * The migration that seeded one exam's objectives is named by this project's own convention:
 * `V<N>__seed_cncf_<examCode>_certification_track.sql`. Finding it by that name, rather than by
 * cross-referencing exam_code through catalog_certification_exam and catalog_exam_objective by
 * their shared track_version_id, trades a little generality for not parsing SQL joins by regex.
 * A future non-CNCF or non-naming-convention pack will need this generalised, not silently matched.
 */
function findObjectiveMigration(examCode) {
  const needle = `seed_cncf_${examCode.toLowerCase()}_certification_track.sql`;
  const match = readdirSync(MIGRATION_DIR).find((name) => name.endsWith(needle));
  return match ? join(MIGRATION_DIR, match) : null;
}

/** Every (objective_key, title) the migration's own INSERT recorded, in the order it lists them. */
function readSeededObjectives(migrationPath) {
  const sql = readFileSync(migrationPath, "utf8");
  const block = /INSERT INTO certforge\.catalog_exam_objective \(track_version_id, objective_key, title, source_ref\) VALUES\s*([\s\S]*?);/.exec(sql);
  if (!block) return [];
  const objectives = [];
  const row = /\('[^']*',\s*'([^']+)',\s*'((?:[^'\\]|\\.)*)',/g;
  for (const m of block[1].matchAll(row)) {
    objectives.push({ key: m[1], title: m[2].replace(/''/g, "'") });
  }
  return objectives;
}

const lines = [
  "# Certification source packet",
  "",
  "Generated by `content/build-certification-source-packet.mjs` from each certification pack's",
  "`pack.json` and the migration that seeded its exam's objectives. **Regenerate it rather than",
  "editing it.**",
  "",
  "## What this is, and is not",
  "",
  "For every certification question, the objective it claims, printed beside the one verified",
  "reading this project recorded for that exam: the provider's own version name, the date read, the",
  "HTTPS page, and a `sha256:` digest of it (content-policy.md, \"Certification source governance\").",
  "",
  "**This is not a second verification.** It juxtaposes what `pack.json` and the seeding migration",
  "already say; it re-reads neither the provider's page nor the question. A reviewer still judges",
  "whether a claimed objective is real and whether the answer is correct -- this only puts the",
  "source in front of them instead of leaving it in the catalog-admin API. Objectives with no",
  "question are a visible gap by this project's own policy (ADR 0017), not a defect in this packet.",
  "",
];

for (const packDir of certificationPackDirs()) {
  const { manifest, questions } = readManifestPack(packDir);
  const cert = manifest.certification;
  lines.push(`## ${manifest.trackSlug}`, "");
  lines.push(
    `**${cert.provider} ${cert.examCode}.** Verified ${cert.verifiedOn} against`,
    `\`${cert.providerVersion}\`. Digest \`${cert.snapshotDigest}\`.`,
    "",
  );

  const migrationPath = findObjectiveMigration(cert.examCode);
  const seeded = migrationPath ? readSeededObjectives(migrationPath) : [];
  const claimed = new Map();
  for (const question of questions) {
    for (const key of question.objectiveKeys ?? []) {
      if (!claimed.has(key)) claimed.set(key, []);
      claimed.get(key).push(question.name);
    }
  }

  lines.push("| Objective | Title | Claimed by |", "|---|---|---|");
  for (const objective of seeded) {
    const by = claimed.get(objective.key);
    lines.push(`| \`${objective.key}\` | ${objective.title} | ${by ? by.map((n) => `\`${n}\``).join(", ") : "_none yet_"} |`);
  }
  if (seeded.length === 0) {
    lines.push("| _(no seeding migration found by the `seed_cncf_<examCode>_certification_track.sql` naming convention)_ | | |");
  }
  const covered = seeded.filter((o) => claimed.has(o.key)).length;
  lines.push("", `${covered} of ${seeded.length} seeded objectives claimed by a published question.`, "");
}

writeFileSync(OUT, lines.join("\n") + "\n");
console.log(`${OUT}: ${certificationPackDirs().length} certification pack(s) written`);
